function write_gathered_mat(data_dir, stem, run_header, parameters, ...
    error_by_degree, res_by_degree, nudev_by_degree, mesh_list, ...
    degree_list, var_names)
% Every degree in one file, for convergence plots.
%
% errors is level-by-variable-by-degree, so a log-log plot of variable v
% across degrees is squeeze(errors(:, v, :)) against h -- no reshaping and
% no reading back through the tables.
[eoc_by_degree, h] = deal(zeros(size(error_by_degree)), []);
for jj = 1:numel(degree_list)
    [eoc_page, h] = compute_eoc(error_by_degree(:, :, jj), mesh_list);
    % compute_eoc drops the first level (a rate needs two), so pad the head
    % with NaN and keep every array indexed by level throughout the file.
    eoc_by_degree(:, :, jj) = [nan(1, size(error_by_degree, 2)); eoc_page];
end
data = struct( ...
    "stem",             stem, ...
    "degrees",          degree_list, ...
    "h",                h, ...
    "errors",           error_by_degree, ...
    "eoc",              eoc_by_degree, ...
    "variable_names",   var_names, ...
    "residue",          res_by_degree, ...
    "normal_deviation", nudev_by_degree, ...
    "parameters",       parameters, ...
    "run_header",       run_header);
save(data_dir + stem + ".mat", "-struct", "data");
fprintf("gathered data: %s.mat (k = %s)\n", stem, join(string(degree_list), ","));
end
